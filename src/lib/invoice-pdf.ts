import { jsPDF } from "jspdf";
import type { Invoice, ShopProfile } from "@/lib/db";
import { formatDateTime } from "@/lib/format";

const page = { width: 210, height: 297, margin: 18 };

function money(value: number): string {
  return `INR ${value.toFixed(2)}`;
}

export function createInvoicePdfFile(invoice: Invoice, shop: ShopProfile | null): File {
  const pdf = new jsPDF({ unit: "mm", format: "a4" });
  const contentWidth = page.width - page.margin * 2;
  const ticket = invoice.id.slice(0, 8).toUpperCase();
  let y = page.margin;

  const drawHeader = (continued = false) => {
    pdf.setTextColor(33, 75, 52);
    pdf.setFont("helvetica", "bold");
    pdf.setFontSize(20);
    pdf.text(shop?.shopName || "Kokan POS Store", page.margin, y);
    y += 7;

    pdf.setTextColor(105, 121, 109);
    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(9);
    const contact = [shop?.area, shop?.phone].filter(Boolean).join(" · ");
    if (contact) {
      pdf.text(contact, page.margin, y);
      y += 5;
    }

    pdf.setDrawColor(224, 232, 223);
    pdf.line(page.margin, y, page.width - page.margin, y);
    y += 9;
    pdf.setTextColor(39, 61, 46);
    pdf.setFont("helvetica", "bold");
    pdf.setFontSize(14);
    pdf.text(continued ? "RECEIPT (CONTINUED)" : "SALES RECEIPT", page.margin, y);
    y += 7;
    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(9);
    pdf.text(`Receipt #${ticket}`, page.margin, y);
    pdf.text(formatDateTime(invoice.createdAt), page.width - page.margin, y, { align: "right" });
    y += 7;
    if (invoice.customerName) {
      pdf.text(`Customer: ${invoice.customerName}`, page.margin, y);
      y += 6;
    }
    if (invoice.customerPhone) {
      pdf.text(`Phone: ${invoice.customerPhone}`, page.margin, y);
      y += 6;
    }
    y += 3;
    pdf.setFillColor(241, 246, 240);
    pdf.rect(page.margin, y - 5, contentWidth, 9, "F");
    pdf.setFont("helvetica", "bold");
    pdf.setFontSize(8);
    pdf.setTextColor(74, 91, 77);
    pdf.text("ITEM", page.margin + 2, y);
    pdf.text("QTY", page.width - 80, y, { align: "right" });
    pdf.text("PRICE", page.width - 48, y, { align: "right" });
    pdf.text("TOTAL", page.width - page.margin - 2, y, { align: "right" });
    y += 7;
  };

  drawHeader();
  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(9);
  pdf.setTextColor(54, 68, 57);

  for (const item of invoice.items) {
    const nameLines = pdf.splitTextToSize(item.name, 85) as string[];
    const rowHeight = Math.max(7, nameLines.length * 4.5);
    if (y + rowHeight + 55 > page.height - page.margin) {
      pdf.addPage();
      y = page.margin;
      drawHeader(true);
      pdf.setFont("helvetica", "normal");
      pdf.setFontSize(9);
      pdf.setTextColor(54, 68, 57);
    }

    pdf.text(nameLines, page.margin + 2, y);
    pdf.text(`${item.quantity} ${item.unit}`, page.width - 80, y, { align: "right" });
    pdf.text(money(item.unitPrice), page.width - 48, y, { align: "right" });
    pdf.text(money(item.lineTotal), page.width - page.margin - 2, y, { align: "right" });
    y += rowHeight;
    pdf.setDrawColor(237, 240, 235);
    pdf.line(page.margin, y - 2, page.width - page.margin, y - 2);
  }

  if (y + 55 > page.height - page.margin) {
    pdf.addPage();
    y = page.margin;
    drawHeader(true);
    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(9);
    pdf.setTextColor(54, 68, 57);
  }
  y += 6;
  pdf.setFontSize(9);
  pdf.setTextColor(104, 115, 105);
  pdf.text("Subtotal", page.width - 70, y);
  pdf.text(money(invoice.subtotal), page.width - page.margin, y, { align: "right" });
  y += 6;
  if (invoice.discount > 0) {
    pdf.text("Discount", page.width - 70, y);
    pdf.text(`- ${money(invoice.discount)}`, page.width - page.margin, y, { align: "right" });
    y += 6;
  }
  pdf.setDrawColor(218, 228, 217);
  pdf.line(page.width - 75, y, page.width - page.margin, y);
  y += 7;
  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(13);
  pdf.setTextColor(34, 96, 59);
  pdf.text("TOTAL", page.width - 70, y);
  pdf.text(money(invoice.totalAmount), page.width - page.margin, y, { align: "right" });
  y += 8;
  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(9);
  pdf.setTextColor(88, 102, 91);
  pdf.text(`Paid by: ${invoice.paymentMode.toUpperCase()}`, page.width - 70, y);
  y += 16;
  pdf.setFontSize(10);
  pdf.setTextColor(71, 102, 76);
  pdf.text("Thank you for shopping local!", page.width / 2, y, { align: "center" });
  pdf.setFontSize(8);
  pdf.setTextColor(133, 144, 134);
  pdf.text("This receipt was generated by Kokan POS.", page.width / 2, y + 6, { align: "center" });

  const blob = pdf.output("blob");
  return new File([blob], `receipt-${ticket}.pdf`, { type: "application/pdf" });
}

export function downloadInvoicePdf(file: File): void {
  const url = URL.createObjectURL(file);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = file.name;
  anchor.click();
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
}
